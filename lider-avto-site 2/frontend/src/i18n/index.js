const CATEGORY_NAME_TO_SLUG = {
  'Dvigatel': 'dvigatel',
  'Tormoz': 'tormoz',
  'Filtrlar': 'filtrlar',
  'Osma (podveska)': 'osma',
  'Elektr': 'elektr',
  'Yoritish': 'yoritish',
  'Yogʻlar va suyuqliklar': 'yoglar',
  'Sovitish': 'sovitish',
  'Uzatma (transmissiya)': 'uzatma',
  'Kuzov': 'kuzov',
  'Salon': 'salon',
}

const state = reactive({
  locale: localStorage.getItem(STORAGE_KEY) || 'uz',
})

export function useI18n() {
  const locale = computed({
    get: () => state.locale,
    set: (v) => {
      state.locale = v
      localStorage.setItem(STORAGE_KEY, v)
      document.documentElement.setAttribute('lang', v)
    },
  })

  function t(key) {
    return messages[state.locale]?.[key] ?? messages.uz[key] ?? key
  }

  function setLocale(l) {
    locale.value = l
  }

  function categoryName(cat) {
    if (!cat) return ''
    const name = typeof cat === 'string' ? cat : (cat.name || '')
    const slug = (typeof cat === 'object' && cat.slug) || CATEGORY_NAME_TO_SLUG[name] || ''
    if (!slug) return name
    const key = `cat_${slug}`
    const val = t(key)
    return val === key ? name : val
  }

  const locales = [
    { code: 'uz', label: 'UZ' },
    { code: 'ru', label: 'RU' },
    { code: 'en', label: 'EN' },
  ]

  return { locale, t, setLocale, locales, categoryName }
}
